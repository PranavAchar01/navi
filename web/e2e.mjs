import { chromium } from "playwright";
const url = process.argv[2] ?? "http://127.0.0.1:8444";
const file = process.argv[3];
const ask = process.argv[4] ?? "where is the remote?";
const wait = Number(process.argv[5] ?? 45);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 860 } });
page.on("console", (m) => m.type() === "error" && console.log("console error:", m.text()));
page.on("pageerror", (e) => console.log("page error:", e.message));
await page.goto(url);
await page.screenshot({ path: "/tmp/ms-0-start.png" });
if (process.env.MODE) await page.click(`#modes [data-mode="${process.env.MODE}"]`);
await page.setInputFiles("#file", file);
await page.waitForTimeout(wait * 1000);
await page.screenshot({ path: process.env.SHOT_LIVE ?? "/tmp/ms-1-live.png" });
await page.fill("#ask-input", ask);
await page.press("#ask-input", "Enter");
await page.waitForTimeout(6000);
await page.screenshot({ path: "/tmp/ms-2-answer.png" });
console.log("answer:", await page.textContent("#answer-text"));
console.log("map:", await page.textContent("#map-count"));
await browser.close();
